"""Monaco-style DVH tables for desktop preview, XLSX and CSV export.

The exporter consumes calculated results, never screenshot reference values.
Unsupported Monaco CI values remain blank.
"""
from __future__ import annotations

import json
import traceback
from pathlib import Path


HEADERS = ['Structure', 'Volume (cm³)', 'Min. Dose (cGy)', 'Max. Dose (cGy)',
           'Mean Dose (cGy)', 'Ref. Vol. (cm³)', 'Ref. Vol. (%)', 'Ref. Dose (cGy)',
           'Dosimetric Criterion', 'Calculated Result', '% in Volume', 'Is in SS',
           'Heterogeneity Index', 'Conformity Index']


def criterion_text(goal):
    def number(value):
        return f'{value:g}' if value is not None else '?'
    text = f'{goal.get("metric") or "Unknown"} {goal.get("operator") or "?"} '
    text += number(goal.get('limit')) + (' ' + goal['limit_unit'] if goal.get('limit_unit') else '')
    tolerance = goal.get('tolerance')
    if tolerance:
        sign = '-' if goal.get('operator') == '>=' else '+'
        text += f' ({sign}{number(tolerance)})'
    # Preserve the secondary bound when the mean-dose goal is compound.
    secondary = goal.get('raw', {}).get('MeanDoseMaximum', '-1')
    if goal.get('goal_type') == 3 and secondary not in ('-1', 'INF', '+INF'):
        text += f'; Dmean <= {secondary} cGy'
    return text


def _matches(goal, reference):
    query = reference['query']
    kind = goal['goal_type']
    if query['quantity'] == 'dose' and kind in (9, 10, 11, 12):
        return float(goal['raw']['Dose']) == query['value']
    if query['quantity'] == 'relative_volume' and kind in (5, 7):
        return float(goal['raw']['Volume']) == query['value']
    return False


def _rows_and_statuses(result):
    rows, statuses = [], []
    for structure in result['structures']:
        base = [structure['structure'], structure['volume_cm3'], structure['min_dose_cgy'],
                structure['max_dose_cgy'], structure['mean_dose_cgy'], None, None, None,
                None, None, structure['percent_in_volume'],
                'yes' if structure['is_in_ss'] else 'no', structure['heterogeneity_index'], None]
        pending = list(structure['criterion_results'])

        def append(row, criterion=None):
            if criterion is not None:
                row[8], row[9] = criterion_text(criterion['goal']), criterion['actual']
                pending.remove(criterion)
            rows.append(row)
            statuses.append(criterion['indicator'] if criterion else None)

        initial = next((c for c in pending if c['goal']['goal_type'] in (1, 2, 3, 4, 13, 14)), None)
        append(base, initial)
        for reference in structure['reference_requests']:
            row = [None] * len(HEADERS)
            row[5:8] = [reference['volume_cm3'], reference['volume_percent'], reference['dose_cgy']]
            criterion = next((c for c in pending if _matches(c['goal'], reference)), None)
            append(row, criterion)
        for criterion in list(pending):
            row = [None] * len(HEADERS)
            goal, actual = criterion['goal'], criterion['actual']
            kind = goal['goal_type']
            volume = structure['volume_cm3']
            # Monaco also displays reference triplets generated by Dx/Vdose
            # criteria, in addition to separately saved reference requests.
            if actual is not None and kind in (5, 6, 7, 8):
                requested = float(goal['raw']['Volume'])
                relative = requested if kind in (5, 7) else requested / 1000 / volume * 100
                row[5:8] = [relative / 100 * volume, relative, actual]
            elif actual is not None and kind in (9, 10, 11, 12):
                relative = actual if kind in (9, 11) else actual / volume * 100
                row[5:8] = [relative / 100 * volume, relative, float(goal['raw']['Dose'])]
            append(row, criterion)
    return rows, statuses


def display_rows(result):
    """Retain repeated reference requests and align matching criteria by query."""
    return _rows_and_statuses(result)[0]


def export_dvh_xlsx(result, destination, *, source=''):
    """Write a formatted Monaco-style table, retaining numeric precision.

    openpyxl is optional and imported only when exporting XLSX.
    Unsupported values stay blank; patient-supplied names stay literal text.
    """
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter

    book = Workbook()
    sheet = book.active
    sheet.title = 'DVH Statistics'
    sheet.append([f'HyperIO DVH reconstruction — {result["plan"]}'])
    sheet.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(HEADERS))
    sheet.append(['Reconstructed saved dose; Monaco CI unavailable. See Provenance for policies and limitations.'])
    sheet.merge_cells(start_row=2, start_column=1, end_row=2, end_column=len(HEADERS))
    sheet.append(HEADERS)
    rows, statuses = _rows_and_statuses(result)
    formats = {2: '0.000', 3: '0.0', 4: '0.0', 5: '0.0', 6: '0.000',
               7: '0.00', 8: '0.0', 11: '0.00', 13: '0.00', 14: '0.00'}
    colours = {'green': 'C6EFCE', 'yellow': 'FFEB9C', 'red': 'FFC7CE'}
    for index, (values, status) in enumerate(zip(rows, statuses), 4):
        sheet.append(values)
        for cell in sheet[index]:
            if isinstance(cell.value, str):
                cell.data_type = 's'
            cell.font = Font(name='Calibri', size=11)
            cell.alignment = Alignment(vertical='top', wrap_text=True)
            if values[0] is not None:
                cell.fill = PatternFill('solid', fgColor='DCE6F1')
            cell.number_format = formats.get(cell.column, 'General')
        if values[8] is not None:
            # The result unit follows the criterion, rather than its column.
            criterion_unit = next((c['goal'].get('limit_unit') for s in result['structures']
                                   for c in s['criterion_results'] if criterion_text(c['goal']) == values[8]), None)
            sheet.cell(index, 10).number_format = {'cGy': '0.0', 'cm3': '0.000'}.get(criterion_unit, '0.00')
        if status in colours:
            sheet.cell(index, 10).fill = PatternFill('solid', fgColor=colours[status])
        sheet.row_dimensions[index].height = 30
    for cell in sheet[3]:
        cell.fill = PatternFill('solid', fgColor='CCD7E0')
        cell.font = Font(bold=True)
        cell.alignment = Alignment(wrap_text=True, vertical='center')
    for column, width in enumerate([24, 17, 19, 19, 19, 18, 18, 19, 46, 20, 17, 12, 23, 22], 1):
        sheet.column_dimensions[get_column_letter(column)].width = width
    sheet.row_dimensions[3].height = 32
    sheet.freeze_panes = 'B4'
    sheet.sheet_view.showGridLines = False
    sheet.sheet_properties.pageSetUpPr.fitToPage = True
    sheet.page_setup.orientation = 'landscape'
    sheet.page_setup.paperSize = sheet.PAPERSIZE_A3
    sheet.page_setup.fitToWidth, sheet.page_setup.fitToHeight = 1, 0
    sheet.print_title_rows = '1:3'
    provenance = book.create_sheet('Provenance')
    entries = [('Source', str(source)), ('Plan', result['plan']),
               ('Plan member path', result.get('plan_path', '')),
               ('Calculation', 'HyperIO reconstruction from saved native dose; no dose recalculation in Monaco'),
               ('Sampling', json.dumps(result['sampling'], default=str)),
               ('Dose grid', json.dumps(result['dose_grid'], default=str)),
               ('CI', 'Unavailable: Monaco formula has not been established')]
    entries += [('Limitation', text) for text in result['limitations']]
    entries += [('Criterion colours', 'Reconstructed primary-bound results, not clinical approval; blank means unavailable')]
    for key, value in entries:
        provenance.append([key, value])
        provenance.cell(provenance.max_row, 2).data_type = 's'
        provenance.cell(provenance.max_row, 2).alignment = Alignment(wrap_text=True, vertical='top')
        provenance.row_dimensions[provenance.max_row].height = 45
    provenance.column_dimensions['A'].width = 25
    provenance.column_dimensions['B'].width = 110
    book.save(Path(destination))


def export_dvh_csv(result, destination, *, source=''):
    """Write a UTF-8 CSV table and a JSON provenance sidecar.

    Prefix formula-like text with an apostrophe for spreadsheet import safety.
    Numeric values retain full precision and unavailable values stay empty.
    The sidecar is named <destination>.provenance.json.
    """
    import csv

    def safe_cell(value):
        if isinstance(value, str) and value.lstrip().startswith(('=', '+', '-', '@')):
            return "'" + value
        return value

    destination = Path(destination)
    metadata = {key: value for key, value in result.items() if key != 'structures'}
    metadata['source'] = str(source)
    metadata['criterion_results'] = [
        {'structure': row['structure'], 'results': row['criterion_results']}
        for row in result['structures']]
    metadata['display'] = {'dose_unit': 'cGy', 'volume_unit': 'cm3',
                           'relative_volume_unit': '%', 'conformity_index': 'unavailable',
                           'text_policy': 'Formula-like strings prefixed with an apostrophe'}
    # Serialize metadata before creating either output file.
    serialized = json.dumps(metadata, indent=2, default=str, allow_nan=False) + '\n'
    with destination.open('w', encoding='utf-8-sig', newline='') as stream:
        writer = csv.writer(stream)
        writer.writerow(HEADERS)
        writer.writerows([safe_cell(value) for value in row] for row in display_rows(result))
    sidecar = destination.with_name(destination.name + '.provenance.json')
    sidecar.write_text(serialized, encoding='utf-8')
    return sidecar


def safe_filename_component(value):
    """Make a portable filename component from a plan identity."""
    import re
    value = re.sub(r'[\\/:*?"<>|\x00-\x1f]', '_', str(value)).strip(' .')
    if not value:
        value = '_'
    if value.split('.')[0].upper() in {'CON', 'PRN', 'AUX', 'NUL', *(f'COM{i}' for i in range(1, 10)), *(f'LPT{i}' for i in range(1, 10))}:
        value = '_' + value
    return value


def calculate_for_export(source, selected, boundary):
    """Calculate a plan and retain its saved structure display order."""
    from .dvh import calculate_plan_dvh

    result = calculate_plan_dvh(source, selected['name'], plan_path=selected['path'], boundary=boundary)
    result['plan_path'] = selected['path']
    order = {name: i for i, name in enumerate(result['structure_order'])}
    result['structures'].sort(key=lambda row: order[row['structure']])
    return result


def batch_export_dvh(source, plans, destination, *, boundary='include'):
    """Export each calculable plan, reporting failures without overwriting files."""
    destination = Path(destination)
    outcomes = []
    names = {}
    for plan in plans:
        if not plan.get('error'):
            name = '-'.join(safe_filename_component(plan[key]) for key in ('patient_id', 'studyset', 'name')) + '.xlsx'
            names.setdefault(name.casefold(), []).append(plan['path'])
    for plan in plans:
        path = plan['path']
        try:
            if plan.get('error'):
                raise ValueError(plan['error'])
            name = '-'.join(safe_filename_component(plan[key]) for key in ('patient_id', 'studyset', 'name')) + '.xlsx'
            if len(names[name.casefold()]) > 1:
                raise ValueError(f'Filename collision: {name}')
            target = destination / name
            result = calculate_for_export(source, plan, boundary)
            # Reserve the output exclusively; remove a partial file if export fails.
            with target.open('xb'):
                pass
            try:
                export_dvh_xlsx(result, target, source=source)
            except Exception:
                target.unlink()
                raise
            outcomes.append({'path': path, 'output': str(target), 'error': None})
        except Exception as exc:
            outcomes.append({'path': path, 'output': None, 'error': str(exc),
                             'traceback': traceback.format_exc()})
    return outcomes
